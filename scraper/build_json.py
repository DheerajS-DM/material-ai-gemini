def generate_expanded_dataset() -> List[Dict[str, Any]]:
    """Generates a rich, realistic dataset by expanding seed materials across variants."""
    expanded: List[Dict[str, Any]] = []
    expanded.extend(SEED_MATERIALS)

    # Generate realistic alloy & polymer grade variations
    variations_config = [
        # (Base ID, Name Prefix, Yield Multiplier, UTS Multiplier, E Multipliers, Cost Multiplier)
        ("mat-al-6061-t6", "Aluminum 6061-O (Annealed)", 0.35, 0.48, 1.0, 0.85, False),
        ("mat-al-6061-t6", "Aluminum 6063-T6", 0.75, 0.77, 0.99, 0.90, True),
        ("mat-al-7075-t6", "Aluminum 7050-T7451", 0.93, 0.92, 1.0, 1.15, True),
        ("mat-al-7075-t6", "Aluminum 2024-T3", 0.68, 0.82, 1.02, 0.95, False),
        ("mat-steel-1020-cold-drawn", "AISI 1045 Carbon Steel (Normalized)", 1.10, 1.35, 1.0, 1.05, False),
        ("mat-steel-1020-cold-drawn", "AISI 4140 Chromoly Steel (QT)", 2.40, 2.30, 1.01, 1.80, False),
        ("mat-steel-1020-cold-drawn", "AISI 4340 Alloy Steel (Heat Treated)", 2.80, 2.70, 1.01, 2.20, False),
        ("mat-ss-304", "Stainless Steel 302", 0.95, 0.98, 1.0, 0.92, True),
        ("mat-ss-304", "Stainless Steel 410 (Martensitic)", 1.95, 1.50, 1.03, 1.10, True),
        ("mat-ti-6al-4v", "Titanium Grade 2 (Unalloyed CP)", 0.39, 0.41, 0.92, 0.55, True),
        ("mat-ti-6al-4v", "Titanium Ti-3Al-2.5V (Grade 9)", 0.67, 0.66, 0.93, 0.75, True),
        ("mat-polycarbonate-unfilled", "Polycarbonate + 20% Glass Fiber", 1.45, 1.50, 2.30, 1.40, True),
        ("mat-peek-unfilled", "PEEK + 30% Carbon Fiber", 2.20, 2.10, 4.80, 2.10, True),
        ("mat-nylon-66", "Nylon 6/6 + 30% Glass Fiber", 1.90, 1.95, 3.00, 1.50, True),
        ("mat-cfrp-high-modulus", "CFRP Ultra-High Modulus (Pitch-Based)", 1.20, 1.10, 2.10, 2.50, True),
    ]

    for base_id, new_name, y_mult, uts_mult, e_mult, c_mult, corr in variations_config:
        base = next((m for m in SEED_MATERIALS if m["material_id"] == base_id), None)
        if not base:
            continue
        
        var_record = dict(base)
        var_record["material_id"] = f"{base_id}-var-{len(expanded)}"
        var_record["name"] = new_name
        var_record["yield_strength_mpa"] = round(base["yield_strength_mpa"] * y_mult, 1) if base.get("yield_strength_mpa") else None
        var_record["ultimate_tensile_strength_mpa"] = round(base["ultimate_tensile_strength_mpa"] * uts_mult, 1) if base.get("ultimate_tensile_strength_mpa") else None
        var_record["youngs_modulus_gpa"] = round(base["youngs_modulus_gpa"] * e_mult, 1) if base.get("youngs_modulus_gpa") else None
        var_record["cost_per_kg_usd"] = round(base["cost_per_kg_usd"] * c_mult, 2) if base.get("cost_per_kg_usd") else None
        var_record["corrosion_resistant"] = corr
        expanded.append(var_record)

    return expanded

def save_database(data: List[Dict[str, Any]], target_path: str):
    """Saves material list as pretty JSON file."""
    os.makedirs(os.path.dirname(target_path), exist_ok=True)
    with open(target_path, "w", encoding="utf-8") as f:
        json.dump(data, f, indent=2)
    print(f"Successfully saved {len(data)} material records to {target_path}")

